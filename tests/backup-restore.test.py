class BackupRestoreTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root = Path(tempfile.mkdtemp(prefix="clipforge-backup-test-"))
        cls.root.chmod(0o700)
        cls.env = {k: v for k, v in os.environ.items() if not k.startswith("PG") and
                   k not in ("DATABASE_URL", "RESTORE_TARGET_DATABASE_URL")}
        cls.bin = Path(subprocess.check_output(["pg_config", "--bindir"], text=True).strip())
        cls.env.update(PGHOST=str(cls.root), PGPORT="5432", PGUSER="postgres", PGDATABASE="postgres")
        cls.server_started = False
        try:
            cls.command("initdb", "-D", str(cls.root / "data"), "--username=postgres", "--auth-local=trust", "--auth-host=reject", "--no-locale", "--encoding=UTF8")
            cls.command("pg_ctl", "-D", str(cls.root / "data"), "-l", str(cls.root / "postgres.log"), "-o", f"-F -k {cls.root} -h '' -p 5432", "-w", "start")
            cls.server_started = True
            cls.sql("create role fixture_reader nologin nobypassrls")
        except Exception:
            cls.tearDownClass()
            raise

    @classmethod
    def command(cls, name, *args, input=None):
        p = subprocess.run([str(cls.bin / name), *args], env=cls.env, input=input,
                           text=True, capture_output=True, timeout=40)
        if p.returncode:
            raise AssertionError(f"Local fixture command failed: {name}")
        return p.stdout.strip()

    @classmethod
    def sql(cls, query, db="postgres"):
        return cls.command("psql", "-XqAt", "-v", "ON_ERROR_STOP=1", "-d", db, input=query)

    @classmethod
    def tearDownClass(cls):
        if cls.server_started:
            cls.command("pg_ctl", "-D", str(cls.root / "data"), "-m", "fast", "-w", "stop")
        shutil.rmtree(cls.root)

    def setUp(self):
        self.work = Path(tempfile.mkdtemp(prefix="case-", dir=self.root))
        self.work.chmod(0o700)
        self.source = "clipforge_fixture_" + uuid.uuid4().hex
        self.target = "clipforge_restore_" + uuid.uuid4().hex
        self.sql(f'create database "{self.source}"')
        self.sql(f'create database "{self.target}"')
        self.sql('drop schema public', self.target)  # Empty, freshly created fixture DB only.
        self.sql(FIXTURE, self.source)
        self.store = self.work / "storage"
        self.store.mkdir(mode=0o700)
        self.password = secrets.token_urlsafe(24)  # Synthetic, never an actual credential.
        self.passfile = self.work / "passfile"
        self.passfile.write_text("*:*:*:*:" + self.password + "\n")
        self.passfile.chmod(0o600)
        self.services = self.work / "services"
        self.write_services()
        self.spy = self.work / "bin"
        self.spy.mkdir(mode=0o700)
        self.calls = self.work / "calls.jsonl"
        for name in ("psql", "pg_dump", "pg_restore"):
            wrapper = self.spy / name
            wrapper.write_text(f'''#!/usr/bin/env python3
import json, os, sys
from pathlib import Path
with open({str(self.calls)!r}, 'a') as log:
    log.write(json.dumps({{"tool": {name!r}, "argv": sys.argv[1:], "pg": {{k:v for k,v in os.environ.items() if k.startswith("PG")}}}}) + '\\n')
if {name!r} == "pg_dump" and Path({str(self.work / "interrupt")!r}).exists():
    for arg in sys.argv:
        if arg.startswith("--file="): Path(arg[7:]).write_bytes(b"incomplete fixture")
    sys.stderr.write(Path(os.environ['PGPASSFILE']).read_text())
    sys.exit(130)
os.execv({str(self.bin / name)!r}, [{name!r}] + sys.argv[1:])
''')
            wrapper.chmod(0o700)
        self.settings = dict(self.env)
        self.settings.update(PATH=str(self.spy) + ":" + self.env["PATH"],
            PGSERVICEFILE=str(self.services), PGPASSFILE=str(self.passfile), BACKUP_PGSERVICE="source",
            RESTORE_PGSERVICE="target", BACKUP_SOURCE_KIND="synthetic-local", ALLOW_SYNTHETIC_BACKUP="YES",
            ALLOW_DISPOSABLE_RESTORE="YES", RESTORE_TARGET_LABEL="disposable", RESTORE_ARTIFACT_TRUSTED="YES",
            TRUSTED_BACKUP_HOST="YES", BACKUP_STORAGE_VERIFIED_ENCRYPTED="YES", BACKUP_SCOPE_APPROVED="YES",
            BACKUP_DIR=str(self.store), EXPECTED_PRODUCTION_DATABASE_NAME=self.source,
            EXPECTED_PRODUCTION_SERVER_ADDRESS="local", EXPECTED_RESTORE_DATABASE_NAME=self.target,
            EXPECTED_RESTORE_SERVER_ADDRESS="local")
        # YES above tests the storage-attestation branch, NOT real encryption.
        # These disposable files contain only synthetic fixtures.

    def write_services(self, source_host=None, target_host=None, extra=""):
        self.services.write_text(f"[source]\nhost={source_host or self.root}\nport=5432\nuser=postgres\ndbname={self.source}\nsslmode=disable\n{extra}\n[target]\nhost={target_host or self.root}\nport=5432\nuser=postgres\ndbname={self.target}\nsslmode=disable\n")
        self.services.chmod(0o600)

    def invoke(self, action, **updates):
        environment = self.settings | updates
        p = subprocess.run(["bash", str(REPO / "scripts/db" / ("backup-production.sh" if action == "backup" else "restore-verify.sh"))],
            env=environment, capture_output=True, text=True, timeout=35)
        self.assertNotIn(self.password, p.stdout + p.stderr)
        self.assertNotIn("Traceback", p.stderr)
        if self.calls.exists():
            calls = self.calls.read_text()
            self.assertNotIn(self.password, calls)
            self.assertNotIn("postgresql://", calls)
            for call in map(json.loads, calls.splitlines()):
                self.assertNotIn("PGPASSWORD", call["pg"])
                self.assertEqual(call["pg"]["PGHOST"], str(self.root))
                self.assertIn(call["pg"]["PGDATABASE"], (self.source, self.target))
                self.assertNotIn("PGSERVICEFILE", call["pg"])
        return p

    def backup(self):
        p = self.invoke("backup")
        self.assertEqual(p.returncode, 0, p.stderr)
        bundles = list(self.store.glob("clipforge-*"))
        self.assertEqual(len(bundles), 1)
        self.settings["BACKUP_BUNDLE"] = str(bundles[0])
        return bundles[0]

    def deny(self, action, **updates):
        p = self.invoke(action, **updates)
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("BLOCKED:", p.stderr)
        return p

    def refresh_checksums(self, bundle):
        (bundle / "complete.json").write_text(json.dumps({p.name: tooling.digest(p) for p in bundle.iterdir() if p.name != "complete.json"}))

    def test_01_real_fixture_dump_restore_counts_content_rls_and_history(self):
        before = self.sql("select jsonb_agg(to_jsonb(i) order by id) from public.content_items i", self.source)
        bundle = self.backup()
        meta = json.loads((bundle / "inventory.json").read_text())
        self.assertEqual(meta["kind"], "synthetic-local")
        self.assertTrue(all(p.stat().st_mode & 0o777 == 0o600 for p in bundle.iterdir()))
        self.assertEqual(bundle.stat().st_mode & 0o777, 0o700)
        self.assertNotIn("vault", (bundle / "archive.list").read_text())
        self.assertNotIn("auth users", (bundle / "archive.list").read_text())
        p = self.invoke("restore")
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("VERIFIED: scoped local restore", p.stdout)
        self.assertEqual(before, self.sql("select jsonb_agg(to_jsonb(i) order by id) from public.content_items i", self.target))
        self.assertEqual(before, self.sql("select jsonb_agg(to_jsonb(i) order by id) from public.content_items i", self.source))
        self.assertEqual(self.sql("select version from supabase_migrations.schema_migrations", self.target), "209901010001")
        self.assertEqual(self.sql("select relrowsecurity and relforcerowsecurity from pg_class where oid='public.content_items'::regclass", self.target), "t")
        self.assertEqual(self.sql("select count(*) from pg_namespace where nspname in ('auth','vault')", self.target), "0")
        # Grants deliberately excluded. For synthetic semantic checking only,
        # grant this existing test role SELECT then prove the restored policy.
        self.sql("grant usage on schema public to fixture_reader; grant select on public.content_items to fixture_reader", self.target)
        self.assertEqual(self.sql("set role fixture_reader; select count(*) from public.content_items", self.target), "1")
        calls = list(map(json.loads, self.calls.read_text().splitlines()))
        dump = next(c for c in calls if c["tool"] == "pg_dump" and "--version" not in c["argv"])
        self.assertIn("default_transaction_read_only=on", dump["pg"]["PGOPTIONS"])
        self.assertTrue(any(a.startswith("--snapshot=") for a in dump["argv"]))
        restore = next(c for c in calls if "--single-transaction" in c["argv"])
        self.assertIn("--exit-on-error", restore["argv"])
        self.assertNotIn("--clean", restore["argv"])

