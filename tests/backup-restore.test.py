    def test_18_production_connection_validation_without_network(self):
        # Inspect only the pure connection builder; never open a production socket.
        cert = self.work / "synthetic-cert"
        cert.write_text("Synthetic placeholder: never used for a TLS connection")
        self.services.write_text(f"[source]\nhost=db.{tooling.PRODUCTION_REF}.supabase.co\nport=5432\nuser=postgres\ndbname=postgres\nsslmode=verify-full\nsslrootcert={cert}\n")
        config = self.settings | {"PRODUCTION_IDENTITY_VERIFIED": "YES", "EXPECTED_PRODUCTION_PROJECT_REF": tooling.PRODUCTION_REF}
        with patch.dict(os.environ, config, clear=True):
            child, settings = tooling.connection("backup")
            self.assertEqual(settings["host"], f"db.{tooling.PRODUCTION_REF}.supabase.co")
            self.assertIn("default_transaction_read_only=on", child["PGOPTIONS"])
        for change in ({"PRODUCTION_IDENTITY_VERIFIED": ""}, {"EXPECTED_PRODUCTION_PROJECT_REF": "wrong"}):
            with patch.dict(os.environ, config | change, clear=True):
                with self.assertRaises(tooling.Refused):
                    tooling.connection("backup")
        self.services.write_text(self.services.read_text().replace("sslmode=verify-full", "sslmode=require"))
        with patch.dict(os.environ, config, clear=True):
            with self.assertRaises(tooling.Refused):
                tooling.connection("backup")
        self.assertFalse(self.calls.exists())

